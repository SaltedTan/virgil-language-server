// The result stream of run.cjs --results: one vscode run's JSON Lines events,
// by the contract in test/e2e/RESULTS.md. run.cjs, the outer launcher, calls
// it, and it alone writes the stream. Each launch's suite.cjs appends its
// observations to a file of the launch's own (see observations.cjs), which
// launch() reads once the launch has ended. The launcher's own checks come
// from what run.cjs observed: the preflight, each VSIX installation, each
// start of VS Code, and the evidence after each window closed.

const { spawnSync } = require('node:child_process');
const crypto = require('node:crypto');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { pathToFileURL } = require('node:url');

const REPO = path.resolve(__dirname, '../../../..');
const MANIFEST = path.join(REPO, 'test/e2e/coverage.json');
const SUITE = 'vscode';
const PURPOSES = ['release', 'development', 'compatibility', 'canary', 'demo'];
const PREFLIGHT = 'vscode.infrastructure.preflight';
const INSTALL = 'vscode.infrastructure.vsix-install';
const LAUNCH = 'vscode.infrastructure.launch';
const SHUTDOWN = 'vscode.shutdown.window-close';
const RECOVERY = 'vscode.recovery.window-close';
// The checks that run.cjs observes; suite.cjs observes the others.
const LAUNCHER = new Set([PREFLIGHT, INSTALL, LAUNCH, SHUTDOWN, RECOVERY]);
// The profile of each launch. The workspace and workspace-recovery launches
// split the workspace checks, so that neither approaches the 120-second limit,
// and together report the profile's launcher checks. The recovery-close launch,
// which closes the window during a recovery, opens the fixture as the workspace
// launches do, and RECOVERY alone observes it.
const PROFILES = {
  'single-file': 'single-file', workspace: 'workspace', 'workspace-recovery': 'workspace', 'recovery-close': 'workspace',
};
const OBSERVATIONS = 'observations.jsonl';
// The failure codes that suite.cjs gives (see observations.cjs).
const SUITE_CODES = new Set(['wait-timeout', 'error', 'restore-failed']);
// The longest reason or observation that the stream keeps.
const LIMIT = 4000;
// The second line of a launcher that scripts/v3c.sh writes for the JVM target,
// as test/e2e/nvim/results.py matches it.
const JVM_LAUNCHER_MARKER = '# Generated by scripts/v3c.sh for the JVM target; do not edit.';

function utc(ms) {
  return new Date(ms).toISOString();
}

function remoteSsh() {
  // Loaded when used: that runner imports run.cjs, which imports this module.
  return require('./remote-ssh/run.cjs');
}

function unavailable(reason) {
  return { value: null, unavailable: reason };
}

function isUnavailable(value) {
  return value !== null && typeof value === 'object' && 'unavailable' in value;
}

// The planned observations of a vscode run, from the manifest: each check of
// the suite in each of its profiles, once, with the vsix condition's checks
// exactly in a run that installs a VSIX.
function plan(manifest, vsix) {
  const suite = manifest.suites.find((s) => s.id === SUITE);
  const profiles = new Map(suite.profiles.map((profile) => [profile.id, profile]));
  const keys = [];
  const levels = {};
  for (const check of manifest.checks) {
    if (!check.suites.includes(SUITE)) continue;
    if (check.when !== null && check.when !== 'vsix') {
      throw new Error(`results.cjs: ${check.id} has the condition ${check.when}, which the vscode writer doesn't decide`);
    }
    levels[check.id] = check.level;
    if (check.when === 'vsix' && !vsix) continue;
    for (const profile of check.profiles.filter((id) => profiles.has(id))) {
      if (profiles.get(profile).repeated) {
        throw new Error(`results.cjs: profile ${profile} is repeated, which the vscode writer doesn't run`);
      }
      keys.push({ id: check.id, profile, iteration: 1 });
    }
  }
  const order = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
  keys.sort((a, b) => order(a.id, b.id) || order(a.profile, b.profile) || a.iteration - b.iteration);
  return { keys, levels };
}

// Replaces the machine's absolute paths in text from VS Code and the suite,
// longest first, so that the stream names files as the fixture and the
// repository do. extra has more [path, name] pairs, such as the Remote-SSH
// test's directories.
function scrubber(work, extra = []) {
  const pairs = [[REPO, '<repo>'], [os.homedir(), '~'], ...extra];
  if (work !== undefined) pairs.push([work, '<work>']);
  const forms = [];
  for (const [file, name] of pairs) {
    if (typeof file !== 'string' || file.length <= 1) continue;
    const url = pathToFileURL(file).href;
    for (const form of new Set([file, url, decodeURI(url)])) forms.push([form, name]);
  }
  forms.sort((a, b) => b[0].length - a[0].length);
  return (text) => {
    let result = String(text);
    for (const [form, name] of forms) result = result.split(form).join(name);
    return result.length > LIMIT ? `${result.slice(0, LIMIT)} [${result.length - LIMIT} more characters]` : result;
  };
}

function run(command, args) {
  const result = spawnSync(command, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], timeout: 10000 });
  return result.status === 0 ? result.stdout : undefined;
}

// The server's build target, from its executable's header: jvm for the JVM
// target's launcher script.
function target(file) {
  const header = Buffer.alloc(20);
  const fd = fs.openSync(file, 'r');
  let length;
  try {
    length = fs.readSync(fd, header, 0, 20, 0);
  } finally {
    fs.closeSync(fd);
  }
  return targetOf(header.subarray(0, length), () => fs.readFileSync(file, 'latin1'));
}

// The build target of an executable whose first bytes are header; text reads
// the whole file, as Latin-1, for a script's second line.
function targetOf(header, text) {
  const length = header.length;
  if (header.toString('latin1', 0, 2) === '#!') {
    const second = text().split('\n')[1]?.replace(/\r$/, '');
    if (second === JVM_LAUNCHER_MARKER) return 'jvm';
  }
  if (length >= 20 && header.readUInt32BE(0) === 0x7f454c46 && header[4] === 2 && header.readUInt16LE(18) === 0x3e) {
    return 'x86-64-linux';
  }
  if (length >= 8 && header.readUInt32LE(0) === 0xfeedfacf && header.readUInt32LE(4) === 0x01000007) return 'x86-64-darwin';
  return unavailable('the server is neither an x86-64 ELF nor an x86-64 Mach-O executable, nor a JVM launcher');
}

function executable(file) {
  try {
    fs.accessSync(file, fs.constants.X_OK);
    return fs.statSync(file).isFile();
  } catch {
    return false;
  }
}

// The server, given as virgil-lsp's path, or unavailable for a reason, and
// the worker that it starts: virgil-lsp-worker beside its physical path.
function serverProvenance(server) {
  const result = {
    versionText: null, version: null, sourceRevision: null, virgilRevision: null,
    target: null, sha256: null, workerSha256: null,
  };
  if (typeof server !== 'string' || !executable(server)) {
    const missing = unavailable(typeof server === 'string' ? 'virgil-lsp is missing, or not executable' : server.reason);
    return { ...result, versionText: missing, target: missing, sha256: missing, workerSha256: missing };
  }
  const { sha256 } = remoteSsh();
  result.sha256 = sha256(server);
  result.target = target(server);
  const text = run(server, ['--version'])?.replace(/\n+$/, '');
  if (!text) {
    result.versionText = unavailable('virgil-lsp --version failed');
  } else {
    result.versionText = text;
    result.version = /^virgil-lsp (\S+)$/.exec(text.split('\n')[0])?.[1] ?? null;
    result.sourceRevision = /^\s*source revision: (\S+)\s*$/m.exec(text)?.[1] ?? null;
    result.virgilRevision = /^\s*virgil revision: (\S+)\s*$/m.exec(text)?.[1] ?? null;
  }
  const worker = path.join(path.dirname(fs.realpathSync(server)), 'virgil-lsp-worker');
  result.workerSha256 = executable(worker) ? sha256(worker)
    : unavailable('virgil-lsp-worker is missing, or not executable, beside the server');
  return result;
}

// The VSIX's name, SHA-256, and version, from its extension/package.json.
function vsixProvenance(vsix) {
  const { readZipEntry, sha256 } = remoteSsh();
  try {
    const { version } = JSON.parse(readZipEntry(vsix, 'extension/package.json'));
    if (typeof version !== 'string' || version === '') throw new Error('its package.json has no version');
    return { name: path.basename(vsix), sha256: sha256(vsix), version };
  } catch (error) {
    return unavailable(`the VSIX could not be read: ${error.message}`);
  }
}

// The checkout's HEAD, its tree, and whether tracked files changed, apart
// from changes inside the vendor/virgil checkout, as results.py records them.
function harness() {
  const git = (...args) => run('git', ['-C', REPO, ...args]);
  const commit = (text) => (/^[0-9a-f]{40}$/.test(text?.trim() ?? '') ? text.trim() : null);
  const status = git('status', '--porcelain', '--untracked-files=no', '--ignore-submodules=dirty');
  return {
    revision: commit(git('rev-parse', '--verify', 'HEAD')),
    tree: commit(git('rev-parse', '--verify', 'HEAD^{tree}')),
    dirty: status === undefined ? null : status.trim() !== '',
  };
}

function machine(serverTarget) {
  if (process.platform === 'linux') {
    let kernel = '';
    try {
      kernel = fs.readFileSync('/proc/sys/kernel/osrelease', 'utf8');
    } catch {
      // Not available.
    }
    return {
      os: kernel.toLowerCase().includes('microsoft') ? 'wsl' : 'linux',
      release: os.release() || 'unknown',
      arch: os.machine() || 'unknown',
      cpu: os.cpus()[0]?.model?.trim() || null,
      translation: null,
    };
  }
  if (process.platform === 'darwin') {
    const arm64 = run('sysctl', ['-n', 'hw.optional.arm64'])?.trim() === '1';
    return {
      os: 'macos',
      release: run('sw_vers', ['-productVersion'])?.trim() || os.release() || 'unknown',
      arch: os.machine() || 'unknown',
      cpu: run('sysctl', ['-n', 'machdep.cpu.brand_string'])?.trim() || null,
      translation: arm64 && serverTarget === 'x86-64-darwin' ? 'rosetta-2' : null,
    };
  }
  throw new Error(`results.cjs: no vscode setup runs on ${process.platform}`);
}

// GitHub Actions' run, or null outside it.
function ci(env) {
  if (env.GITHUB_ACTIONS !== 'true') return null;
  const { GITHUB_SERVER_URL: server, GITHUB_REPOSITORY: repository, GITHUB_RUN_ID: id } = env;
  if (!(server && repository && id)) return null;
  const attempt = Number(env.GITHUB_RUN_ATTEMPT ?? '1');
  const image = [env.ImageOS, env.ImageVersion].filter(Boolean).join(' ');
  return {
    runUrl: `${server}/${repository}/actions/runs/${id}`, jobUrl: null,
    attempt: Number.isInteger(attempt) && attempt > 0 ? attempt : 1, runnerImage: image || null,
  };
}

// run.cjs's command, with the repository's paths relative to its root and
// other paths as placeholders, so that no machine's path is published. args
// are run.cjs's arguments, resolved against cwd.
function commandOf(args, cwd, env) {
  return commandWords(args, cwd, {
    words: env.npm_lifecycle_event === 'test:e2e' ? ['npm', 'run', 'test:e2e', '--']
      : ['node', 'clients/vscode/test/e2e/run.cjs'],
    placeholders: { '--vsix': '<vsix>', '--logs': '<logs>' },
    valued: ['--release', '--purpose'],
    positional: '<server>',
  });
}

// A launcher's command, after words: each option of placeholders with its
// path relative to the repository's root, if it is inside it, and otherwise
// the placeholder; --results always as <results>; the options in valued
// with their values; and a positional argument as a path, or positional.
function commandWords(args, cwd, { words, placeholders, valued, positional }) {
  const relative = (word, placeholder) => {
    const inside = path.relative(REPO, path.resolve(cwd, word));
    return inside === '..' || inside.startsWith(`..${path.sep}`) || path.isAbsolute(inside) ? placeholder
      : inside.split(path.sep).join('/');
  };
  const paths = { ...placeholders, '--results': '<results>' };
  const result = [...words];
  for (let i = 0; i < args.length; i++) {
    const [option, inline] = args[i].startsWith('--') ? args[i].split(/=(.*)/s) : [args[i]];
    if (option in paths || valued.includes(option)) {
      const value = inline ?? args[++i] ?? '<missing>';
      const shown = option === '--results' ? '<results>'
        : option in paths ? relative(value, paths[option]) : value;
      result.push(option, shown);
    } else {
      result.push(args[i].startsWith('-') ? args[i] : relative(args[i], positional));
    }
  }
  return result;
}

class Results {
  // file: the stream, which this empties at once. vsix: the VSIX's path, if
  // the run installs one. now and env stand in for the clock and the
  // environment in tests.
  constructor({ file, vsix, release = null, purpose = 'development', command, editorVersion, manifest = MANIFEST,
    now = Date.now, env = process.env }) {
    if (!PURPOSES.includes(purpose)) throw new Error(`--purpose takes one of ${PURPOSES.join(', ')}, not ${purpose}`);
    if (release === '') throw new Error('--release takes a version, not an empty string');
    fs.writeFileSync(file, '');
    this.file = file;
    this.vsix = vsix;
    this.release = release;
    this.purpose = purpose;
    this.command = command;
    this.editorVersion = editorVersion;
    this.manifestFile = manifest;
    ({ keys: this.keys, levels: this.levels } = plan(JSON.parse(fs.readFileSync(manifest, 'utf8')), vsix !== undefined));
    this.now = now;
    this.env = env;
    this.launchedAt = now();
    this.scrub = scrubber();
    // What run.cjs has learned for the run-start's provenance (see start).
    this.info = {};
    this.started = false;
    this.seq = 0;
    // Events before the run-start, which start() writes after it.
    this.queue = [];
    this.reported = new Map();
    this.firstFailure = undefined;
    this.issues = [];
    this.attempts = {};
    // The workspace launch's outcome, when it passed and deferred its launcher
    // checks to the workspace-recovery launch, which shares its profile.
    this.pendingWorkspace = undefined;
    this.unavailableProvenance = false;
  }

  set work(work) {
    this.scrub = scrubber(work);
  }

  write(event) {
    const line = { schema: 1, event: event.event, runId: this.runId, seq: this.seq, ...event };
    fs.appendFileSync(this.file, `${JSON.stringify(line)}\n`);
    this.seq += 1;
  }

  // Writes the run-start, from this.info, then the events before it. run.cjs
  // calls it once the server is known: at once for an external server, and
  // after the single-file launch's installation for the VSIX's bundled one.
  // A run that stops before that gets the run-start from end(), with what
  // could be obtained.
  start() {
    if (this.started) return;
    const { server, virgilRoot, fixture, settings } = this.info;
    const serverFields = serverProvenance(server ?? { reason: 'the launcher stopped before it found the server' });
    const host = machine(isUnavailable(serverFields.target) ? null : serverFields.target);
    const setup = { linux: 'vscode-linux', macos: 'vscode-macos', wsl: 'vscode-wsl' }[host.os];
    const { sha256, treeSha256 } = remoteSsh();
    const configuration = settings === undefined ? {}
      : Object.fromEntries(['single-file', 'workspace'].map((profile) =>
        [profile, crypto.createHash('sha256').update(settings).digest('hex')]));
    const vsix = this.vsix === undefined ? null : vsixProvenance(this.vsix);
    const fixtureSha256 = typeof fixture === 'string' ? treeSha256(fixture)
      : unavailable(fixture?.reason ?? 'the launcher stopped before it copied the fixture');
    const started = this.now();
    this.runId = `vscode-${utc(started).replace(/[-:]/g, '').replace(/\.\d+Z$/, 'Z')}-${crypto.randomBytes(4).toString('hex')}`;
    this.unavailableProvenance = [...Object.values(serverFields), vsix, fixtureSha256].some(isUnavailable);
    this.write({
      event: 'run-start', time: utc(started), release: this.release, purpose: this.purpose, suite: SUITE, setup,
      lane: this.env.GITHUB_ACTIONS === 'true' && this.env.GITHUB_JOB ? this.env.GITHUB_JOB : 'local',
      command: this.command, coverageSha256: sha256(this.manifestFile),
      expected: this.keys, facts: {},
      provenance: {
        server: serverFields, archive: null, vsix, clientMode: this.vsix === undefined ? 'source' : 'vsix',
        harness: harness(),
        editor: { name: 'vscode', version: this.editorVersion ?? null, commit: null, arch: null },
        client: host, host, transport: { kind: 'local', topology: 'local', extensionHost: 'local' },
        pins: [], configurationSha256: configuration, fixtureSha256,
        virgilRootSha256: typeof virgilRoot === 'string' && fs.existsSync(virgilRoot) ? treeSha256(virgilRoot) : null,
        runtimes: { node: process.versions.node }, ci: ci(this.env),
      },
      attestation: null,
    });
    this.started = true;
    for (const event of this.queue.splice(0)) this.write(event);
  }

  // Records one observation, unless it is unplanned or a repeat, which are
  // issues of the run.
  check(id, profile, status, { startedAt, endedAt = this.now(), observation, reason = null, failureCode = null }) {
    const key = `${id} ${profile}`;
    if (!this.keys.some((k) => k.id === id && k.profile === profile)) {
      this.issues.push(`${id} (${profile}) was observed, but the run doesn't plan it`);
      return;
    }
    if (this.reported.has(key)) {
      this.issues.push(`${id} (${profile}) was observed again`);
      return;
    }
    this.reported.set(key, status);
    if (status === 'fail') this.firstFailure ??= id;
    const event = {
      event: 'check', time: utc(endedAt), id, profile, iteration: 1, status, level: this.levels[id],
      startedAt: utc(startedAt ?? endedAt), durationMs: Math.max(0, Math.round(endedAt - (startedAt ?? endedAt))),
      reason: reason === null ? null : this.scrub(reason) || status, expectation: null, failureCode,
      observation: this.scrub(observation) || status, artifacts: [],
    };
    if (this.started) this.write(event);
    else this.queue.push(event);
  }

  // The preflight: the VSIX exists, the server and worker are executable, and
  // VS Code is available. failure is why it failed, if it did.
  preflight({ endedAt = this.now(), failure, observation }) {
    if (failure === undefined) {
      this.check(PREFLIGHT, 'wrapper', 'pass', { startedAt: this.launchedAt, endedAt, observation });
    } else {
      this.check(PREFLIGHT, 'wrapper', 'fail', {
        startedAt: this.launchedAt, endedAt, observation: failure, reason: failure, failureCode: 'preflight',
      });
    }
  }

  // A new attempt of the launch called name, in directory dir: run.cjs records
  // what it observes in the returned object, and the suite writes its
  // observations to its observations file. A retry replaces the attempt that
  // failed, whose observations don't count.
  attempt(name, dir) {
    const outcome = { attempt: (this.attempts[name]?.attempt ?? 0) + 1, observations: path.join(dir, OBSERVATIONS) };
    this.attempts[name] = outcome;
    return outcome;
  }

  // Writes the observations of the launch called name, from its last attempt,
  // once it has ended or thrown error. The workspace and workspace-recovery
  // launches share the workspace profile: a workspace launch that passed
  // defers its launcher checks, and the workspace-recovery launch reports them
  // once, over both launches.
  launch(name, error) {
    const outcome = this.attempts[name];
    if (outcome === undefined) return;
    const profile = PROFILES[name];
    const lines = this.suiteObservations(outcome.observations);
    const failed = (id, observation, failureCode, startedAt) => this.check(id, profile, 'fail', {
      startedAt, observation, reason: observation, failureCode,
    });
    const retried = outcome.attempt > 1 ? ', in its retry' : '';
    const { installation, launch, close } = outcome;
    // A bundled server is known once the VSIX is installed.
    if (outcome.server !== undefined && typeof this.info.server !== 'string') {
      this.info.server = outcome.server;
      this.info.virgilRoot = path.join(path.dirname(outcome.server), 'virgil', 'lib');
    }
    if (name === 'recovery-close') {
      for (const entry of lines) this.issues.push(`suite.cjs reported ${entry.id ?? 'an observation'} in the recovery-close launch, which has no checks of the suite's own`);
      const startedAt = installation?.startedAt ?? launch?.startedAt;
      if (installation !== undefined && !installation.passed) {
        failed(RECOVERY, `the VSIX's installation ${installation.detail}`, 'installation', startedAt);
      } else if (error !== undefined && (launch === undefined || launch.passed) && close === undefined) {
        failed(RECOVERY, `the launch failed: ${error.message}`, 'error', startedAt);
      } else if (launch !== undefined && !launch.passed) {
        failed(RECOVERY, `VS Code ${launch.detail}`, launch.serverExitFailed ? 'servers-left' : code(launch), startedAt);
      } else if (close?.problem !== undefined) {
        failed(RECOVERY, close.problem, close.unreadable ? 'evidence-unreadable' : 'recovery', startedAt);
      } else if (close !== undefined) {
        this.check(RECOVERY, profile, 'pass', {
          startedAt, endedAt: close.endedAt,
          observation: 'the killed server\'s start and the recovery\'s were the only starts; the extension host\'s '
            + 'terminating log released the recovery, which the client logged; the recovered server received '
            + 'initialize, initialized, the didOpen of bad.v3 before exit, and shutdown and then exit last, and '
            + `exited with status 0${retried}`,
        });
      }
      return;
    }
    if (name === 'workspace') {
      // A workspace launch that failed at any stage reports the profile's
      // launcher checks at once. One that passed leaves them to the
      // workspace-recovery launch, which shares the profile.
      const incomplete = error !== undefined || installation?.passed === false
        || !launch?.passed || close === undefined || close.problem !== undefined;
      if (incomplete) {
        this.pendingWorkspace = undefined;
        this.emitLaunch(name, profile, lines, outcome, error, retried);
      } else {
        this.suiteLaunchObservations(name, profile, lines);
        this.pendingWorkspace = { outcome, retried };
      }
      return;
    }
    if (name === 'workspace-recovery') {
      this.emitRecoveryLaunch(profile, lines, outcome, error, retried);
      return;
    }
    this.emitLaunch(name, profile, lines, outcome, error, retried);
  }

  // Writes a launch's installation, suite observations, and launcher checks,
  // for a launch that reports them itself: single-file, and a workspace launch
  // that failed before a workspace-recovery launch could combine them.
  emitLaunch(name, profile, lines, { installation, launch, close }, error, retried) {
    const failed = (id, observation, failureCode, startedAt) => this.check(id, profile, 'fail', {
      startedAt, observation, reason: observation, failureCode,
    });
    if (installation !== undefined) {
      if (installation.passed) {
        this.check(INSTALL, profile, 'pass', {
          ...installation,
          observation: `--install-extension installed the VSIX into the launch's empty extensions directory and exited with status 0 after ${seconds(installation)}${retried}`,
        });
      } else {
        failed(INSTALL, `--install-extension ${installation.detail}`, code(installation), installation.startedAt);
      }
    }
    this.suiteLaunchObservations(name, profile, lines);
    if (launch === undefined) {
      if (error !== undefined && (installation === undefined || installation.passed)) {
        failed(LAUNCH, `the launch failed: ${error.message}`, 'error', installation?.endedAt);
      }
      return;
    }
    if (launch.passed) {
      this.check(LAUNCH, profile, 'pass', {
        ...launch,
        observation: `VS Code exited with status 0 after ${seconds(launch)}, within 120 seconds, and its process group exited${retried}`,
      });
    } else {
      failed(LAUNCH, `VS Code ${launch.detail}`, launch.serverExitFailed ? 'servers-left' : code(launch), launch.startedAt);
    }
    if (launch.serverExitFailed) {
      failed(SHUTDOWN, launch.detail, 'servers-left', launch.endedAt);
    } else if (launch.passed && close === undefined && error !== undefined) {
      failed(SHUTDOWN, `the launch failed after VS Code exited: ${error.message}`, 'error', launch.endedAt);
    } else if (close?.problem !== undefined) {
      failed(SHUTDOWN, close.problem, close.unreadable ? 'evidence-unreadable' : 'unclean-exit', close.startedAt);
    } else if (close !== undefined) {
      this.check(SHUTDOWN, profile, 'pass', {
        startedAt: launch.endedAt, endedAt: close.endedAt,
        observation: 'no virgil-lsp or virgil-lsp-worker was left in VS Code\'s process group within 5 seconds of VS Code\'s exit, and '
          + (close.exit === undefined ? 'the output channel logged no server exit' : `the last server exit logged was clean: ${close.exit}`),
      });
    }
  }

  // Writes the workspace profile's launcher checks and the workspace-recovery
  // launch's suite observations, combining the deferred workspace launch's
  // installation, start of VS Code, and clean exit with the recovery launch's.
  // Combined events record the workspace-recovery launch's timestamps and
  // duration, so idle time between the two launches is not counted as part of
  // a single installation, launch, or shutdown window; each observation text
  // reports both launches' results.
  emitRecoveryLaunch(profile, lines, { installation, launch, close }, error, retried) {
    const first = this.pendingWorkspace;
    this.pendingWorkspace = undefined;
    const failed = (id, observation, failureCode, startedAt, endedAt) => this.check(id, profile, 'fail', {
      startedAt, endedAt, observation, reason: observation, failureCode,
    });
    const firstInstallation = first?.outcome.installation;
    const firstLaunch = first?.outcome.launch;
    const firstClose = first?.outcome.close;
    const retryNotes = [
      first?.retried ? 'the workspace launch in its retry' : undefined,
      retried ? 'the workspace-recovery launch in its retry' : undefined,
    ].filter((note) => note !== undefined);
    const retryNote = retryNotes.length === 0 ? '' : `, ${retryNotes.join(' and ')}`;
    if (installation !== undefined || firstInstallation !== undefined) {
      if (installation === undefined) {
        if (error !== undefined) {
          failed(INSTALL, `the workspace-recovery launch failed before installing the VSIX: ${error.message}`, 'error');
          return;
        }
      } else if (!installation.passed) {
        failed(INSTALL, `--install-extension ${installation.detail} in the workspace-recovery launch`, code(installation),
          installation.startedAt, installation.endedAt);
      } else {
        const observation = firstInstallation === undefined
          ? `--install-extension installed the VSIX into the workspace-recovery launch's empty extensions directory and exited with status 0 after ${seconds(installation)}${retryNote}`
          : `--install-extension installed the VSIX into the workspace and workspace-recovery launches' empty extensions directories and exited with status 0 after ${seconds(firstInstallation)} and ${seconds(installation)}${retryNote}`;
        this.check(INSTALL, profile, 'pass', {
          startedAt: installation.startedAt, endedAt: installation.endedAt, observation,
        });
      }
    }
    this.suiteLaunchObservations('workspace-recovery', profile, lines);
    if (launch === undefined) {
      if (error !== undefined && (installation === undefined || installation.passed)) {
        failed(LAUNCH, `the launch failed in the workspace-recovery launch: ${error.message}`, 'error',
          installation?.endedAt);
      }
      return;
    }
    if (!launch.passed) {
      failed(LAUNCH, `VS Code ${launch.detail} in the workspace-recovery launch`,
        launch.serverExitFailed ? 'servers-left' : code(launch), launch.startedAt, launch.endedAt);
    } else {
      const observation = firstLaunch === undefined
        ? `the workspace-recovery launch exited with status 0 after ${seconds(launch)}, within 120 seconds, and its process group exited${retryNote}`
        : `the workspace launch exited with status 0 after ${seconds(firstLaunch)} and the workspace-recovery launch after ${seconds(launch)}, each within 120 seconds, and their process groups exited${retryNote}`;
      this.check(LAUNCH, profile, 'pass', { startedAt: launch.startedAt, endedAt: launch.endedAt, observation });
    }
    if (launch.serverExitFailed) {
      failed(SHUTDOWN, `${launch.detail} in the workspace-recovery launch`, 'servers-left', launch.endedAt);
    } else if (launch.passed && close === undefined && error !== undefined) {
      failed(SHUTDOWN, `the launch failed after VS Code exited in the workspace-recovery launch: ${error.message}`, 'error', launch.endedAt);
    } else if (close?.problem !== undefined) {
      failed(SHUTDOWN, close.problem, close.unreadable ? 'evidence-unreadable' : 'unclean-exit', close.startedAt, close.endedAt);
    } else if (close !== undefined) {
      const exitNote = (entry) => (entry.exit === undefined
        ? 'the output channel logged no server exit'
        : `the last server exit logged was clean: ${entry.exit}`);
      const observation = firstClose === undefined
        ? `no virgil-lsp or virgil-lsp-worker was left in VS Code's process group within 5 seconds of the workspace-recovery launch's exit, and ${exitNote(close)}`
        : `no virgil-lsp or virgil-lsp-worker was left in VS Code's process group within 5 seconds of either the workspace or workspace-recovery launch's exit; workspace: ${exitNote(firstClose)}; workspace-recovery: ${exitNote(close)}`;
      this.check(SHUTDOWN, profile, 'pass', {
        startedAt: launch.endedAt, endedAt: close.endedAt, observation,
      });
    }
  }

  // Writes the suite's observations of a launch, after checking that its
  // profile plans each one and that it wasn't reported before.
  suiteLaunchObservations(name, profile, lines) {
    for (const entry of lines) {
      if (!this.planned(entry.id, profile) || LAUNCHER.has(entry.id)) {
        this.issues.push(`suite.cjs reported ${entry.id}, which the ${name} launch doesn't plan`);
      } else if (entry.status === 'pass') {
        this.check(entry.id, profile, 'pass', entry);
      } else {
        this.check(entry.id, profile, 'fail', entry);
      }
    }
  }

  planned(id, profile) {
    return typeof id === 'string' && this.keys.some((k) => k.id === id && k.profile === profile);
  }

  // The valid observations in a launch's file; a malformed one is an issue.
  suiteObservations(file) {
    let text;
    try {
      text = fs.readFileSync(file, 'utf8');
    } catch (error) {
      if (error.code !== 'ENOENT') this.issues.push(`the suite's observations could not be read: ${this.scrub(error.message)}`);
      return [];
    }
    const lower = this.launchedAt - 1000;
    const upper = this.now() + 1000;
    const { found, issues } = parseObservations(text, {
      time: (value) => Number.isFinite(value) && value >= lower && value <= upper, scrub: this.scrub, writer: 'suite.cjs',
    });
    this.issues.push(...issues);
    return found;
  }

  // Ends the run: the run-start if it is still missing, a skip for each
  // planned check that didn't run after a failure, and the run-end. exitCode
  // is what run.cjs would exit with without --results, cleanup whether the
  // temporary directory and every process group are gone, and issues the
  // launcher's own. Returns run.cjs's exit status: 0 exactly when the run
  // passed.
  end({ exitCode, cleanup, issues = [], error }) {
    this.start();
    this.issues.push(...issues.map((issue) => this.scrub(issue)));
    if (error !== undefined) this.issues.push(`the launcher failed: ${this.scrub(error.message)}`);
    const missing = this.keys.filter((k) => !this.reported.has(`${k.id} ${k.profile}`));
    if (this.firstFailure !== undefined) {
      for (const key of missing) {
        this.check(key.id, key.profile, 'skip', {
          observation: 'not run', reason: `not run: ${this.firstFailure} failed`,
        });
      }
    } else if (missing.length > 0) {
      const more = missing.length > 1 ? ` and ${missing.length - 1} more` : '';
      this.issues.push(`${missing[0].id} (${missing[0].profile})${more} have no check event`);
    }
    const counts = { pass: 0, fail: 0, xfail: 0, xpass: 0, skip: 0 };
    for (const status of this.reported.values()) counts[status] += 1;
    const complete = this.reported.size === this.keys.length;
    const preflightFailed = this.reported.get(`${PREFLIGHT} wrapper`) === 'fail';
    const passed = complete && counts.pass === this.keys.length && exitCode === 0 && cleanup === 'verified'
      && this.issues.length === 0 && !this.unavailableProvenance;
    const status = passed ? 'pass' : this.unavailableProvenance || preflightFailed ? 'unavailable' : 'fail';
    const final = passed ? 0 : exitCode || 1;
    const finished = this.now();
    this.write({
      event: 'run-end', time: utc(finished), complete, status, durationMs: Math.max(0, Math.round(finished - this.launchedAt)),
      expectedCount: this.keys.length, checkCount: this.reported.size, counts, exitCode: final, signal: null, cleanup,
      issues: this.issues,
    });
    const outcome = { pass: 'passed', fail: 'failed', unavailable: 'unavailable' }[status];
    console.log(`\nResults: ${this.file}: run ${outcome} (${this.reported.size} of ${this.keys.length} observations): `
      + Object.entries(counts).map(([name, count]) => `${count} ${name}`).join(', '));
    return final;
  }
}

// The observations in text, the JSON lines that observations.cjs appends,
// each with a time that passes time; writer names who wrote them in issues.
// Returns the valid ones, and an issue for each malformed one and for an
// incomplete last line.
function parseObservations(text, { time, scrub, writer }) {
  const text1 = (value) => typeof value === 'string' && value !== '';
  const found = [];
  const issues = [];
  const lines = text.split('\n');
  if (lines.at(-1) !== '') issues.push(`${writer}'s last observation is incomplete`);
  for (const line of lines.slice(0, -1)) {
    let entry;
    try {
      entry = JSON.parse(line);
    } catch {
      entry = undefined;
    }
    const valid = entry !== null && typeof entry === 'object' && text1(entry.id)
      && time(entry.startedAt) && time(entry.endedAt) && entry.startedAt <= entry.endedAt && text1(entry.observation)
      && (entry.status === 'pass' || (entry.status === 'fail' && text1(entry.reason) && SUITE_CODES.has(entry.failureCode)));
    if (valid) {
      found.push({
        id: entry.id, status: entry.status, startedAt: entry.startedAt, endedAt: entry.endedAt,
        observation: entry.observation, reason: entry.status === 'fail' ? entry.reason : null,
        failureCode: entry.status === 'fail' ? entry.failureCode : null,
      });
    } else {
      issues.push(`${writer} wrote a malformed observation: ${scrub(line).slice(0, 200)}`);
    }
  }
  return { found, issues };
}

function seconds({ startedAt, endedAt }) {
  return `${((endedAt - startedAt) / 1000).toFixed(1)} seconds`;
}

// How a process group that run.cjs ran failed.
function code({ error, timedOut, stopped }) {
  if (error) return 'start-error';
  if (timedOut) return 'deadline';
  return stopped ? 'stopped' : 'exit-status';
}

