// suite.cjs names its checks by string literals, which only a real run
// executes. Every vscode check of coverage.json that the launcher doesn't own
// must be named there, and suite.cjs must name no other vscode ID.
test('suite.cjs names exactly the suite checks of coverage.json', () => {
  const manifest = JSON.parse(fs.readFileSync(path.join(REPO, 'test/e2e/coverage.json'), 'utf8'));
  const planned = manifest.checks.filter((check) => check.suites.includes('vscode')).map((check) => check.id)
    .filter((id) => !LAUNCHER.has(id)).sort();
  const source = fs.readFileSync(path.join(__dirname, 'e2e/suite.cjs'), 'utf8');
  const named = [...new Set([...source.matchAll(/'(vscode\.[a-z0-9.-]+)'/g)].map((match) => match[1]))].sort();
  assert.deepEqual(named, planned);
});

function scratch(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'virgil-extension-host-results-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  return root;
}

// A server that the writer can describe: a JVM launcher script, by its
// second line, that prints a version, with a worker beside it.
function fakeServer(root) {
  const dir = path.join(root, 'server');
  fs.mkdirSync(dir);
  const server = path.join(dir, 'virgil-lsp');
  fs.writeFileSync(server, '#!/bin/sh\n# Generated by scripts/v3c.sh for the JVM target; do not edit.\n'
    + 'echo "virgil-lsp 0.1.0-test"; echo "  source revision: 0123456"\n', { mode: 0o755 });
  fs.writeFileSync(path.join(dir, 'virgil-lsp-worker'), '#!/bin/sh\n', { mode: 0o755 });
  return server;
}

// A VSIX that holds only extension/package.json, written by Python's zipfile.
function fakeVsix(root) {
  const vsix = path.join(root, 'virgil-lsp-vscode-0.1.8.vsix');
  const made = spawnSync('python3', ['-c', 'import sys, zipfile\nwith zipfile.ZipFile(sys.argv[1], "w", zipfile.ZIP_DEFLATED) as z:\n'
    + '    z.writestr("extension/package.json", \'{"name": "virgil-lsp-vscode", "version": "0.1.8"}\')', vsix]);
  assert.equal(made.status, 0, String(made.stderr));
  return vsix;
}

function validate(file) {
  const result = spawnSync('python3', [VALIDATOR, 'validate', file], { encoding: 'utf8' });
  return { status: result.status, output: result.stdout + result.stderr };
}

function events(file) {
  return fs.readFileSync(file, 'utf8').split('\n').filter((line) => line !== '').map((line) => JSON.parse(line));
}

// The check event of id in profile, from a run's stream.
function checkOf(stream, id, profile = 'workspace') {
  return stream.find((event) => event.id === id && event.profile === profile);
}

// A writer for a run, with its run-start written, as run.cjs makes one.
function begin(t, { vsix = false, bundled = false } = {}) {
  const root = scratch(t);
  const server = fakeServer(root);
  const fixture = path.join(root, 'project');
  fs.cpSync(path.join(REPO, 'test/e2e/nvim/fixture'), fixture, { recursive: true });
  const file = path.join(root, 'stream.jsonl');
  t.mock.method(console, 'log', () => {});
  const results = new Results({
    file, vsix: vsix ? fakeVsix(root) : undefined, command: ['node', 'clients/vscode/test/e2e/run.cjs'],
    editorVersion: '1.142.0', env: {},
  });
  results.info.server = bundled ? { reason: 'not installed yet' } : server;
  Object.assign(results.info, { fixture, settings: '{}' });
  results.preflight({ observation: 'VS Code 1.142.0 is available' });
  if (!bundled) results.start();
  return { root, file, results, server };
}

// The suite's checks of a profile, in the plan.
function suiteChecks(results, profile) {
  return results.keys.filter((k) => k.profile === profile && !LAUNCHER.has(k.id)).map((k) => k.id);
}

// One attempt of a launch: the suite's observations, as observations.cjs
// writes them, then what run.cjs observed. times overrides the start and end
// timestamps for install, launch, and close when a test verifies durations.
function launch(results, root, name, { vsix = false, observations, installation = true, exit = true, close = {},
  server, serverExitFailed = false, times } = {}) {
  const dir = path.join(root, `${name}-${(results.attempts[name]?.attempt ?? 0) + 1}`);
  fs.mkdirSync(dir, { recursive: true });
  const observed = results.attempt(name, dir);
  const now = Date.now();
  const span = (range) => (range === undefined ? { startedAt: now, endedAt: now } : { startedAt: range[0], endedAt: range[1] });
  if (vsix) {
    observed.installation = {
      ...span(times?.install), passed: installation, detail: installation ? 'exited with 0' : 'exited with 1',
    };
  }
  if (vsix && !installation) return observed;
  if (server !== undefined) observed.server = server;
  const lines = (observations ?? []).map((entry) => (typeof entry === 'string' ? entry
    : JSON.stringify({ status: 'pass', startedAt: now, endedAt: now, observation: 'every assertion of the check passed', ...entry })));
  fs.writeFileSync(observed.observations, lines.map((line) => `${line}\n`).join(''));
  observed.launch = {
    ...span(times?.launch), passed: exit && !serverExitFailed,
    detail: serverExitFailed ? 'left virgil-lsp (pid 42) running 5 seconds after VS Code exited' : exit ? 'exited with 0' : 'exited with 1',
    error: false, timedOut: false, stopped: serverExitFailed, serverExitFailed,
  };
  if (exit && !serverExitFailed && close !== undefined) observed.close = { ...span(times?.close), ...close };
  return observed;
}

function passes(results, profile) {
  return suiteChecks(results, profile).map((id) => ({ id }));
}

// The six in-session recovery scenarios that the workspace-recovery launch runs.
const WORKSPACE_RECOVERY = new Set([
  'vscode.recovery.restart', 'vscode.recovery.server-path', 'vscode.recovery.write-error',
  'vscode.recovery.lost-framing', 'vscode.recovery.lost-framing-request', 'vscode.recovery.crash-limit',
]);

// The workspace checks that the workspace launch runs, before the split.
function workspaceMain(results) {
  return passes(results, 'workspace').filter((entry) => !WORKSPACE_RECOVERY.has(entry.id));
}

// The workspace checks that the workspace-recovery launch runs.
function workspaceRecoveryChecks(results) {
  return passes(results, 'workspace').filter((entry) => WORKSPACE_RECOVERY.has(entry.id));
}

function passingRun(t, options = {}) {
  const run = begin(t, options);
  const { results, root } = run;
  launch(results, root, 'single-file', { ...options, observations: passes(results, 'single-file'), server: options.bundled ? run.server : undefined });
  results.launch('single-file');
  // As run.cjs does, once the installation has found a bundled server.
  results.start();
  launch(results, root, 'workspace', { ...options, observations: workspaceMain(results) });
  results.launch('workspace');
  launch(results, root, 'workspace-recovery', { ...options, observations: workspaceRecoveryChecks(results) });
  results.launch('workspace-recovery');
  launch(results, root, 'recovery-close', { ...options });
  results.launch('recovery-close');
  return run;
}

test('the suite reporter prints and records each check by the ID that began last', (t) => {
  const root = scratch(t);
  const file = path.join(root, 'observations.jsonl');
  const out = { lines: [], log(line) { this.lines.push(line); }, error(line) { this.lines.push(line.split('\n')[0]); } };
  let clock = 1000;
  const checks = reporter({ file, out, now: () => clock++ });
  checks.begin('vscode.startup.installed-copy');
  checks.passLater();
  checks.begin('vscode.startup.activation');
  checks.begin('vscode.diagnostics.single-file-parser');
  checks.passed();
  // A check that resumes keeps its first start.
  checks.begin('vscode.startup.activation');
  checks.passed();
  checks.flush();
  checks.begin('vscode.configuration.disk-watch');
  const restore = checks.failed(new Error('restoring the state failed'), 'restore-failed');
  assert.equal(restore[REPORTED], true);
  // Reported once only, and nothing reports a failure outside a check.
  checks.failed(restore);
  checks.failed(new Error('outside every check'));
  assert.throws(() => checks.begin('vscode.startup.activation'), /already reported/);
  assert.deepEqual(out.lines, [
    'PASS: vscode.diagnostics.single-file-parser',
    'PASS: vscode.startup.activation',
    'PASS: vscode.startup.installed-copy',
    'FAIL: vscode.configuration.disk-watch: Error: restoring the state failed',
  ]);
  const recorded = fs.readFileSync(file, 'utf8').split('\n').filter(Boolean).map((line) => JSON.parse(line));
  assert.deepEqual(recorded.map((entry) => [entry.id, entry.status, entry.failureCode]), [
    ['vscode.diagnostics.single-file-parser', 'pass', undefined],
    ['vscode.startup.activation', 'pass', undefined],
    ['vscode.startup.installed-copy', 'pass', undefined],
    ['vscode.configuration.disk-watch', 'fail', 'restore-failed'],
  ]);
  assert.equal(recorded[1].startedAt, 1002, 'the activation check keeps its first start');
});

