test('a passing run from source plans no vsix checks, and validates as passed', { skip: !python && 'needs Python 3.9+' }, (t) => {
  const { file, results } = passingRun(t);
  assert.equal(results.end({ exitCode: 0, cleanup: 'verified' }), 0);
  const count = results.keys.length;
  assert.deepEqual(validate(file), {
    status: 0, output: `${file}: valid, run passed (${count} of ${count} observations): ${count} pass, 0 fail, 0 xfail, 0 xpass, 0 skip\n`,
  });
  const stream = events(file);
  assert.equal(stream[0].provenance.clientMode, 'source');
  assert.ok(!stream[0].expected.some((key) => key.id === 'vscode.startup.installed-copy'));
  assert.deepEqual(stream[0].facts, {});
  // Each check once, and the suite's in the order they were reported.
  const checks = stream.filter((event) => event.event === 'check');
  assert.equal(new Set(checks.map((event) => `${event.id} ${event.profile}`)).size, results.keys.length);
});

test('a passing VSIX run with a bundled server plans the vsix checks, and validates as passed', { skip: !python && 'needs Python 3.9+' }, (t) => {
  const { file, results } = passingRun(t, { vsix: true, bundled: true });
  assert.equal(results.end({ exitCode: 0, cleanup: 'verified' }), 0);
  assert.equal(validate(file).status, 0, validate(file).output);
  const [start] = events(file);
  assert.equal(start.provenance.clientMode, 'vsix');
  assert.deepEqual(start.provenance.vsix.version, '0.1.8');
  assert.equal(start.provenance.server.target, 'jvm');
  for (const profile of ['single-file', 'workspace']) {
    assert.ok(start.expected.some((key) => key.id === 'vscode.startup.installed-copy' && key.profile === profile));
    assert.ok(start.expected.some((key) => key.id === 'vscode.infrastructure.vsix-install' && key.profile === profile));
  }
});

test('a failed scenario fails the launch, and the checks that did not run are skipped', { skip: !python && 'needs Python 3.9+' }, (t) => {
  const { root, file, results } = begin(t);
  launch(results, root, 'single-file', { observations: passes(results, 'single-file') });
  const workspace = suiteChecks(results, 'workspace');
  const stopped = workspace.indexOf('vscode.configuration.disk-watch');
  launch(results, root, 'workspace', {
    exit: false,
    observations: [...workspace.slice(0, stopped).map((id) => ({ id })), {
      id: workspace[stopped], status: 'fail', reason: 'restoring the state after it failed', failureCode: 'restore-failed',
    }],
  });
  results.launch('single-file');
  results.launch('workspace');
  assert.equal(results.end({ exitCode: 1, cleanup: 'verified' }), 1);
  const { status, output } = validate(file);
  assert.equal(status, 1, output);
  const count = results.keys.length;
  const passed = results.keys.filter((k) => k.profile !== 'workspace').length + stopped;
  assert.ok(output.endsWith(`: valid, run failed (${count} of ${count} observations): `
    + `${passed} pass, 2 fail, 0 xfail, 0 xpass, ${count - passed - 2} skip\n`), output);
  const stream = events(file);
  const status_ = (id, profile) => stream.find((event) => event.id === id && event.profile === profile)?.status;
  assert.equal(status_('vscode.configuration.disk-watch', 'workspace'), 'fail');
  assert.equal(status_('vscode.infrastructure.launch', 'workspace'), 'fail');
  assert.equal(status_('vscode.restart.clean', 'workspace'), 'skip');
  assert.equal(status_('vscode.shutdown.window-close', 'workspace'), 'skip');
  assert.equal(status_('vscode.recovery.window-close', 'workspace'), 'skip');
  assert.equal(stream.at(-1).status, 'fail');
});

test('a failed preflight leaves the run unavailable, with every other check skipped', { skip: !python && 'needs Python 3.9+' }, (t) => {
  const root = scratch(t);
  const file = path.join(root, 'stream.jsonl');
  t.mock.method(console, 'log', () => {});
  const results = new Results({ file, command: ['node', 'clients/vscode/test/e2e/run.cjs'], env: {} });
  results.info.server = path.join(root, 'missing', 'virgil-lsp');
  results.preflight({ failure: 'build virgil-lsp and virgil-lsp-worker before running the test' });
  assert.equal(results.end({ exitCode: 1, cleanup: 'verified' }), 1);
  const { status, output } = validate(file);
  assert.equal(status, 1, output);
  const stream = events(file);
  assert.equal(stream.at(-1).status, 'unavailable');
  assert.equal(stream[0].provenance.server.sha256.unavailable, 'virgil-lsp is missing, or not executable');
  assert.ok(stream.filter((event) => event.event === 'check').slice(1).every((event) => event.status === 'skip'));
});

test('only the last attempt of a retried launch counts', { skip: !python && 'needs Python 3.9+' }, (t) => {
  const { root, file, results } = begin(t);
  // The first attempt reported a check before VS Code's window went away.
  launch(results, root, 'single-file', { exit: false, observations: [{ id: 'vscode.diagnostics.single-file-parser' }] });
  launch(results, root, 'single-file', { observations: passes(results, 'single-file') });
  results.launch('single-file');
  launch(results, root, 'workspace', { observations: passes(results, 'workspace') });
  results.launch('workspace');
  launch(results, root, 'recovery-close');
  results.launch('recovery-close');
  assert.equal(results.end({ exitCode: 0, cleanup: 'verified' }), 0);
  assert.equal(validate(file).status, 0, validate(file).output);
  const launched = events(file).find((event) => event.id === 'vscode.infrastructure.launch' && event.profile === 'single-file');
  assert.match(launched.observation, /in its retry$/);
});

test('malformed or unplanned observations are issues that fail the run', { skip: !python && 'needs Python 3.9+' }, (t) => {
  const { root, file, results } = begin(t);
  launch(results, root, 'single-file', {
    observations: [...passes(results, 'single-file'), '{"id": "vscode.startup.activation"', { id: 'vscode.rename.apply-undo' }],
  });
  results.launch('single-file');
  launch(results, root, 'workspace', { observations: passes(results, 'workspace') });
  results.launch('workspace');
  launch(results, root, 'recovery-close', { observations: [{ id: 'vscode.recovery.window-close' }] });
  results.launch('recovery-close');
  assert.equal(results.end({ exitCode: 0, cleanup: 'verified' }), 1);
  assert.equal(validate(file).status, 1, validate(file).output);
  const { issues } = events(file).at(-1);
  assert.equal(issues.length, 3, JSON.stringify(issues));
  assert.match(issues[0], /^suite\.cjs wrote a malformed observation/);
  assert.match(issues[1], /vscode\.rename\.apply-undo, which the single-file launch doesn't plan/);
  assert.match(issues[2], /in the recovery-close launch/);
});

test('post-close evidence that could not be read fails the window-close check by its ID', { skip: !python && 'needs Python 3.9+' }, (t) => {
  const { root, file, results } = begin(t);
  launch(results, root, 'single-file', {
    observations: passes(results, 'single-file'),
    close: { problem: "could not read the output channel's log after the window closed: EACCES", unreadable: true },
  });
  results.launch('single-file');
  assert.equal(results.end({ exitCode: 1, cleanup: 'verified' }), 1);
  assert.equal(validate(file).status, 1, validate(file).output);
  const shutdown = events(file).find((event) => event.id === 'vscode.shutdown.window-close' && event.profile === 'single-file');
  assert.deepEqual([shutdown.status, shutdown.failureCode], ['fail', 'evidence-unreadable']);
});
