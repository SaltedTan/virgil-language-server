// A stand-in VS Code for remote-ssh/run.cjs's launch(): it prints a suite's
// PASS line and exits with 0, except in the first attempt of 1-single-file,
// where it records an unresponsive window, which permits a retry, and exits
// with 1.
const STAND_IN_VSCODE = `#!/bin/sh
for arg; do case "$arg" in --user-data-dir=*) dir="\${arg#--user-data-dir=}";; esac; done
case "$dir" in
*/1-single-file/user-data)
  mkdir -p "$dir/logs"
  echo 'CodeWindow: detected unresponsive' > "$dir/logs/main.log"
  exit 1;;
esac
echo 'PASS: vscode.startup.activation'
`;

// remote-ssh/run.cjs's launch(), with a real Run and a writer, the stand-in
// VS Code, and a stand-in host that answers run.remote by its command:
// samples are the leak check's process listings in turn, clean after them,
// or 'garbage' for one that can't be read; broken, an Error that writing the
// run's configuration throws. calls has each command's kind, its file if it
// has one, and the stage of the launch then.
function standIn(t, { samples = [], broken } = {}) {
  const root = scratch(t);
  t.mock.method(console, 'log', () => {});
  t.mock.method(console, 'error', () => {});
  const runner = require('./e2e/remote-ssh/run.cjs');
  const results = new Results({
    file: path.join(root, 'stream.jsonl'), command: ['node'], editorVersion: '1.142.0', pins: PINS, env: {}, machine: linuxClient,
  });
  const run = new runner.Run({ out: path.join(root, 'out'), bundled: true });
  Object.assign(run, { results, work: path.join(root, 'work'), env: { PATH: process.env.PATH }, settings: {}, target: { alias: 'stand-in', root: '/remote' } });
  results.run = run;
  run.evidence = path.join(run.work, 'evidence');
  fs.mkdirSync(run.evidence, { recursive: true });
  const executable = path.join(root, 'code');
  fs.writeFileSync(executable, STAND_IN_VSCODE, { mode: 0o755 });
  const layout = {
    agent: '/remote/server/.vscode-server', serverNode: '/remote/node', data: '/remote/data', machineSettings: '/remote/data/Machine/settings.json',
    extensionPath: '/remote/extensions/virgil', server: '/remote/virgil-lsp', virgilRoot: '/remote/virgil', fixture: '/remote/fixture',
    project: '/remote/project', tests: '/remote/tests', results: '/remote/results',
  };
  const calls = [];
  const configs = [];
  const answer = (stdout, code = 0) => ({ stdout, stderr: '', code, data: Buffer.from(stdout) });
  run.remote = async (command, { input } = {}) => {
    const stage = Object.values(results.attempts).at(-1)?.stage;
    if (command.includes('run-config.json')) {
      if (broken !== undefined) throw broken;
      configs.push(JSON.parse(input));
      calls.push({ kind: 'config', stage });
      return answer('');
    }
    if (command.includes('exit 44')) {
      const file = /\/remote\/results\/([^' ]+\.json)/.exec(command)[1];
      calls.push({ kind: 'report', file, stage });
      if (file === '1-single-file.json') return answer('', 44);
      return answer(JSON.stringify({ outcome: 'pass', folders: configs.at(-1).folders, seconds: 1.5 }));
    }
    if (command.includes('.observations.jsonl')) {
      const file = /\/remote\/results\/([^' ]+\.observations\.jsonl)/.exec(command)[1];
      calls.push({ kind: 'observations', file, stage });
      const { mode } = configs.at(-1);
      const now = Date.now();
      return answer(observedChecks(results, mode).map((id) => `${JSON.stringify({ id, status: 'pass', startedAt: now, endedAt: now, observation: 'passed' })}\n`).join(''));
    }
    // REMOTE_PROCESSES, which the VS Code Server's node runs with -e.
    if (command.includes(`${layout.serverNode}' -e `) || command.includes(`${process.execPath}' -e `)) {
      const sample = samples.shift() ?? { unidentified: [] };
      calls.push({ kind: 'processes', stage });
      if (sample === 'garbage') return answer('garbage', 1);
      return answer(JSON.stringify({ found: [], host: false, sampledAt: Date.now(), ...sample }));
    }
    calls.push({ kind: 'other', stage });
    return answer('');
  };
  const launch = (name, mode) => runner.launch(run, name, mode, { executable, layout, vsix: { version: '0.1.8' }, repetition: 1 });
  return { calls, configs, launch, results, run };
}

