// A writer, with the launcher's Run as far as its preflight, as
// remote-ssh/run.cjs makes them.
function begin(t, { repeat = 1, bundled = false, archive = false, target = false } = {}) {
  const root = scratch(t);
  const file = path.join(root, 'stream.jsonl');
  t.mock.method(console, 'log', () => {});
  t.mock.method(console, 'error', () => {});
  const values = { vsix: fakeVsix(root, bundled), bundled, repeat };
  if (archive) values.archive = path.join(root, 'virgil-lsp-0.1.0-test-x86-64-linux.tar.gz');
  if (target) values.target = path.join(root, 'target.json');
  const results = new Results({
    file, repeat, command: ['node', 'clients/vscode/test/e2e/remote-ssh/run.cjs'], editorVersion: '1.142.0', pins: PINS, env: {},
    machine: target ? macClient : linuxClient,
  });
  const work = path.join(root, 'work');
  const run = {
    values, tokens: new Set(), work,
    manifest: {
      client: { vscode: { version: '1.142.0', commit: COMMIT }, ssh: { version: 'OpenSSH_9.6p1' } },
      target: { root: target ? '/remote/vrs-1' : path.join(work, 'target'), os: { name: 'Ubuntu 24.04', kernel: 'Linux 6.8.0-45-generic x86_64' } },
    },
  };
  results.run = run;
  results.directories({ work, out: path.join(root, 'out'), remote: run.manifest.target.root });
  if (!bundled) {
    const server = path.join(root, 'server');
    fs.mkdirSync(server);
    fs.writeFileSync(path.join(server, 'virgil-lsp'), LAUNCHER_SCRIPT, { mode: 0o755 });
    fs.writeFileSync(path.join(server, 'virgil-lsp-worker'), '#!/bin/sh\n', { mode: 0o755 });
    if (archive) {
      fs.writeFileSync(values.archive, 'archive');
      fs.writeFileSync(path.join(server, 'manifest.json'), '{}\n');
      run.manifest.server = { archiveSha256: 'b'.repeat(64) };
    }
    results.server({ file: path.join(server, 'virgil-lsp'), worker: path.join(server, 'virgil-lsp-worker'), archiveRoot: archive ? server : undefined });
    run.manifest.virgilRoot = { libTreeSha256: 'd'.repeat(64) };
  }
  return { root, file, results, run };
}

// The suite's and bootstrap.cjs's checks of a launch, in the plan.
function observedChecks(results, profile, iteration = 1) {
  return results.keys.filter((k) => k.profile === profile && k.iteration === iteration && !LAUNCHER.has(k.id)).map((k) => k.id);
}

// One attempt of a launch, as run.cjs records it: the observations file's
// text, then what the launcher observed. A launch passes unless problems,
// left, or error says otherwise; stage is where error was thrown.
function launch(results, name, mode, iteration, { observations, problems = [], codes, left, error, stage, hostExit = true } = {}) {
  const observed = results.attempt(name, mode, iteration);
  const now = Date.now();
  const entries = observations ?? observedChecks(results, mode, iteration).map((id) => ({ id }));
  observed.observations = entries.map((entry) => `${typeof entry === 'string' ? entry
    : JSON.stringify({ status: 'pass', startedAt: now, endedAt: now, observation: 'every assertion of the check passed', ...entry })}\n`).join('');
  observed.exitedAt = now;
  if (mode !== 'probe' && hostExit) observed.hostExit = { problem: left, lingered: false, startedAt: now, endedAt: now };
  if (error === undefined) {
    observed.launch = { problems, codes: codes ?? problems.map(() => 'tests-failed'), startedAt: now, endedAt: now, seconds: 12.5, passLines: 30 };
  } else {
    observed.stage = stage ?? 'launch';
  }
  return observed;
}

// The launcher's checks and launches up to the repetitions, as run.cjs runs
// them, unless a step's failure stops it.
function setUp(results, { bundled = false } = {}) {
  results.passed(streams.PREFLIGHT, 'the tools are on PATH, the host started');
  results.begin(streams.CLIENT_PINS);
  results.passed(streams.CLIENT_PINS, 'the pinned extensions installed');
  results.begin(streams.ARTIFACT_START);
  results.configure('{"client": true}', '{"machine": true}\n');
  results.fixtureSha256 = 'e'.repeat(64);
  if (!bundled) {
    results.versionText = VERSION;
    results.passed(streams.ARTIFACT_START, 'virgil-lsp --version ran on the host');
  }
  results.begin(streams.PROBE);
  launch(results, 'probe', 'probe', 1);
  results.launch('probe');
  results.passed(streams.PROBE, 'the probe ran');
  results.begin(streams.REMOTE_INSTALL);
  results.passed(streams.REMOTE_INSTALL, 'the VSIX installed on the host');
  if (bundled) {
    results.begin(streams.ARTIFACT_START);
    results.versionText = VERSION;
    results.passed(streams.ARTIFACT_START, 'the bundled virgil-lsp --version ran on the host');
  }
  results.start();
}

function tearDown(results, { teardown = true } = {}) {
  results.passed(streams.EVIDENCE, 'the logs were collected');
  if (teardown) results.passed(streams.TEARDOWN, 'the teardown stopped every process of the run');
  else results.failed(streams.TEARDOWN, 'the teardown could not confirm that nothing of the run is left; pid 42 (Xvfb)', 'processes-left');
}

function passingRun(t, options = {}) {
  const run = begin(t, options);
  const { results } = run;
  setUp(results, options);
  for (let repetition = 1; repetition <= (options.repeat ?? 1); repetition++) {
    for (const mode of ['single-file', 'workspace']) {
      launch(results, `${repetition}-${mode}`, mode, repetition);
      results.launch(`${repetition}-${mode}`);
    }
  }
  tearDown(results);
  return run;
}

function passes(file, count) {
  return { status: 0, output: `${file}: valid, run passed (${count} of ${count} observations): ${count} pass, 0 fail, 0 xfail, 0 xpass, 0 skip\n` };
}

