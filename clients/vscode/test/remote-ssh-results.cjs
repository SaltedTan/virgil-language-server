// bootstrap.cjs in a fake remote extension host whose identity checks pass,
// with suite.cjs replaced by one that records a check of its own.
async function bootstrap(root, { mode = 'single-file', observations, extension = true } = {}) {
  const logs = path.join(root, 'logs', 'exthost1');
  fs.mkdirSync(logs, { recursive: true });
  fs.writeFileSync(path.join(logs, 'remoteexthost.log'), `Extension host with pid ${process.pid} started\n`);
  const config = {
    launch: `1-${mode}`, mode, result: path.join(root, 'result.json'), serverNode: '/server/node', project: '/remote/project',
    serverLogs: path.join(root, 'logs'), extensionPath: '/remote/extensions/virgil', extensionVersion: '0.1.8',
    folders: mode === 'workspace' ? ['file:///remote/project'] : null, ...(observations === undefined ? {} : { observations }),
  };
  const printed = [];
  const env = {};
  const vscode = {
    env: { remoteName: 'ssh-remote' },
    ExtensionKind: { UI: 1, Workspace: 2 },
    workspace: { workspaceFolders: config.folders?.map((uri) => ({ uri: { toString: () => uri } })) },
    extensions: {
      getExtension: () => (extension ? { extensionPath: config.extensionPath, packageJSON: { version: '0.1.8' }, extensionKind: 2 } : undefined),
    },
  };
  const files = { ...fs, readFileSync: (file, encoding) => (path.basename(file) === 'run-config.json' ? JSON.stringify(config) : fs.readFileSync(file, encoding)) };
  const { run } = fakes.load('remote-ssh/bootstrap.cjs', {
    'node:fs': files, vscode,
    './observations.cjs': require('./e2e/observations.cjs'),
    './suite.cjs': {
      run: async () => {
        const checks = require('./e2e/observations.cjs').reporter({ file: env.VIRGIL_E2E_OBSERVATIONS, out: { log: (line) => printed.push(line), error() {} } });
        checks.begin('vscode.startup.activation');
        checks.passed();
      },
    },
  }, { execPath: '/server/node', platform: 'linux', env }, { console: { log: (line) => printed.push(line), error: (line) => printed.push(line) } });
  const error = await run().then(() => undefined, (caught) => caught);
  return { error, printed, result: JSON.parse(fs.readFileSync(config.result, 'utf8')) };
}

test('bootstrap.cjs records its identity checks silently, and suite.cjs its own, in the observations file', async (t) => {
  const root = scratch(t);
  const observations = path.join(root, 'observations.jsonl');
  const { error, printed, result } = await bootstrap(root, { observations });
  assert.equal(error, undefined);
  assert.equal(result.outcome, 'pass');
  const recorded = fs.readFileSync(observations, 'utf8').split('\n').filter(Boolean).map((line) => JSON.parse(line));
  assert.deepEqual(recorded.map((entry) => [entry.id, entry.status]), [
    ['ssh.identity.remote-host', 'pass'], ['ssh.identity.folder-mode', 'pass'], ['ssh.identity.extension-copy', 'pass'],
    ['ssh.identity.host-log', 'pass'], ['vscode.startup.activation', 'pass'],
  ]);
  // Only the suite's PASS line, which run.cjs counts.
  assert.deepEqual(printed, ['PASS: vscode.startup.activation']);
});

