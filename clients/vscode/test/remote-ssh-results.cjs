// remote-ssh/run.cjs's options, with process.argv as given.
function options(t, args) {
  const saved = process.argv;
  process.argv = [process.execPath, 'run.cjs', ...args];
  try {
    return require('./e2e/remote-ssh/run.cjs').options();
  } finally {
    process.argv = saved;
  }
}

const linuxOnly = process.platform !== 'linux' && 'runs on Linux';

// Asserts that remote-ssh/run.cjs's options() refuses args with a UsageError
// that matches pattern.
function refused(t, args, pattern) {
  assert.throws(() => options(t, args), (error) => error.constructor.name === 'UsageError' && pattern.test(error.message));
}

test('the result options need --results, a known purpose, and a release, and --results empties its file once they are checked', { skip: linuxOnly }, (t) => {
  const root = scratch(t);
  const usage = (args, pattern) => refused(t, args, pattern);
  usage(['--release', '0.1.0'], /need --results/);
  usage(['--purpose', 'release'], /need --results/);
  usage(['--results', path.join(root, 'a.jsonl'), '--purpose', 'sometimes'], /--purpose takes one of release, development/);
  usage(['--results', path.join(root, 'a.jsonl'), '--release', ''], /--release takes a version/);
  usage(['--results', ''], /--results takes a file/);
  // Without --results, nothing names a stream.
  const vsix = fakeVsix(root, true);
  const plain = options(t, ['--vsix', vsix, '--bundled', '--work-dir', root]);
  assert.deepEqual([plain.results, plain.release, plain.purpose], [undefined, undefined, undefined]);
  // Once the arguments are checked, the stream is emptied, never left as an
  // earlier run's, even in the output directory, which must be empty.
  const stale = path.join(root, 'stale.jsonl');
  fs.writeFileSync(stale, '{"event": "run-start"}\n');
  usage(['--results', stale], /--vsix is required/);
  assert.equal(fs.readFileSync(stale, 'utf8'), '{"event": "run-start"}\n', 'a usage error writes nothing');
  const given = options(t, ['--vsix', vsix, '--bundled', '--work-dir', root, '--results', stale, '--release', '0.1.0', '--purpose', 'release']);
  assert.deepEqual([given.results, given.release, given.purpose], [stale, '0.1.0', 'release']);
  assert.equal(fs.readFileSync(stale, 'utf8'), '');
  const out = path.join(root, 'out');
  const inside = options(t, ['--vsix', vsix, '--bundled', '--work-dir', root, '--out', out, '--results', path.join(out, 'remote-ssh.jsonl')]);
  assert.deepEqual(fs.readdirSync(inside.out), ['remote-ssh.jsonl']);
});

test('--results is emptied before the output directory fails to be made, and is never its manifest.json or summary.txt', { skip: linuxOnly }, (t) => {
  const root = scratch(t);
  const base = ['--vsix', fakeVsix(root, true), '--bundled', '--work-dir', root];
  const stale = path.join(root, 'stale.jsonl');
  const STALE = '{"event": "run-start"}\n';
  const infra = (error) => error.kind === 'infra' && /^could not prepare the output directory: /.test(error.message);
  // An output directory under a regular file, or a regular file itself, ends
  // the run as INFRA, but no earlier stream outlives it.
  const file = path.join(root, 'file');
  fs.writeFileSync(file, '');
  for (const out of [path.join(file, 'out'), file]) {
    fs.writeFileSync(stale, STALE);
    assert.throws(() => options(t, [...base, '--out', out, '--results', stale]), infra);
    assert.equal(fs.readFileSync(stale, 'utf8'), '', out);
  }
  // A full output directory is a usage error, which leaves the file, even in it.
  const full = path.join(root, 'full');
  fs.mkdirSync(full);
  fs.writeFileSync(path.join(full, 'stale.jsonl'), STALE);
  refused(t, [...base, '--out', full, '--results', path.join(full, 'stale.jsonl')], /the output directory is not empty/);
  assert.equal(fs.readFileSync(path.join(full, 'stale.jsonl'), 'utf8'), STALE);
  // The run writes manifest.json and summary.txt in the output directory.
  const out = path.join(root, 'out');
  for (const name of ['manifest.json', 'summary.txt']) {
    refused(t, [...base, '--out', out, '--results', path.join(out, name)], new RegExp(`output directory's ${name.replace('.', '\\.')}`));
  }
  assert.equal(fs.existsSync(out), false, 'a refused --results makes no output directory');
  fs.mkdirSync(out);
  fs.symlinkSync(out, path.join(root, 'link'));
  refused(t, [...base, '--out', out, '--results', path.join(root, 'link', 'summary.txt')], /output directory's summary\.txt/);
  assert.deepEqual(fs.readdirSync(out), []);
});

