repair_case() {  # repair_case <file>...: sets CURSOR and FILES
    mkdir -p "$TMP/repair"
    FILES=()
    for f in "$@"; do
        local out
        out=$TMP/repair/$(basename "$f")
        if grep -q '<|>' "$f"; then
            CURSOR="--cursor=$out:$(grep -bo '<|>' "$f" | head -n 1 | cut -d: -f1)"
        fi
        sed 's/<|>//' "$f" > "$out"
        FILES+=("$out")
    done
}
